export function getSlangMeaning(slang: SlangWord, lang: Language): string {
  const loc = SLANG_LOCALIZATIONS[slang.id]?.[lang];
  if (loc?.meaning) return loc.meaning;
  if (lang === 'de') return slang.meaningDe;
  return slang.meaningEn || slang.meaningDe;
}

export function getSlangLiteral(slang: SlangWord, lang: Language): string | undefined {
  const loc = SLANG_LOCALIZATIONS[slang.id]?.[lang];
  if (loc?.literal) return loc.literal;
  return slang.literalTranslation;
}
